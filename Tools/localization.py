#!/usr/bin/env python3
"""Build native .strings resources and check translation/placeholder coverage.

Source keys live in Localization/catalog.json. Translation rows are
id|English|Japanese|Korean|German|Spanish; literal \\n denotes a newline.
Run with --check in CI. Generated .strings are checked in for Xcode and SPM.
"""
from pathlib import Path
import argparse,json,re,sys
from swift_strings import extract
ROOT=Path(__file__).resolve().parents[1]
LANGUAGES=['en','ja','ko','de','es']
p=argparse.ArgumentParser();p.add_argument('--check',action='store_true');p.add_argument('--allow-missing',action='store_true');args=p.parse_args()
catalog=json.loads((ROOT/'Localization/catalog.json').read_text())
chinese=json.loads((ROOT/'Localization/zh-Hans.json').read_text())
assert set(chinese) <= {str(item['id']) for item in catalog}, 'Unknown Chinese copy ID'
assert all(isinstance(value,str) for value in chinese.values()), 'Chinese copy must be text'
rows={}
for path in sorted((ROOT/'Localization/translations').glob('*.tsv')):
 for line in path.read_text().splitlines():
  if not line:continue
  cells=line.split('|');assert len(cells)==6,(path,line[:80])
  i=int(cells[0]);assert i not in rows,('duplicate',i)
  rows[i]={lang:value.replace('\\n','\n') for lang,value in zip(LANGUAGES,cells[1:])}
errors=[];expected={}
sources = {item['source'] for item in catalog}
for path in list((ROOT/'HeartPro').rglob('*.swift')) + list((ROOT/'Packages/HeartProCore/Sources/HeartProCore').glob('*.swift')):
 for key in extract(path.read_text()):
  if key not in sources: errors.append(f'Uncatalogued string in {path.name}: {key}')
quote=lambda s:json.dumps(s,ensure_ascii=False)
for lang in ['zh-Hans']+LANGUAGES:
 lines=['/* Generated by Tools/localization.py. Edit Localization/translations instead. */']
 for item in catalog:
  value=chinese.get(str(item['id']),item['source']) if lang=='zh-Hans' else rows.get(item['id'],{}).get(lang)
  if value is None:
   if not args.allow_missing:errors.append(f"Missing {lang}: {item['id']}")
   value=item['source']
  if sorted(re.findall(r'\{\d+\}',value))!=sorted(re.findall(r'\{\d+\}',item['source'])):errors.append(f"Placeholder mismatch {lang}: {item['id']}")
  if not value.strip():errors.append(f"Empty {lang}: {item['id']}")
  lines.append(f'{quote(item["source"])} = {quote(value)};')
 expected[ROOT/f'Packages/HeartProCore/Sources/HeartProCore/Resources/{lang}.lproj/Localizable.strings']='\n'.join(lines)+'\n'
permissions=json.loads((ROOT/'Localization/InfoPlist.json').read_text())
for lang in ['zh-Hans']+LANGUAGES:
 values=permissions.get(lang,{})
 if set(values) != {'NSHealthShareUsageDescription','NSHealthUpdateUsageDescription'}: errors.append(f'Missing permission descriptions: {lang}')
 expected[ROOT/f'HeartPro/Resources/{lang}.lproj/InfoPlist.strings']='\n'.join(f'{quote(k)} = {quote(v)};' for k,v in values.items())+'\n'
for path,content in expected.items():
 if args.check:
  if not path.exists() or path.read_text()!=content:errors.append(f"Stale resource: {path.relative_to(ROOT)}")
 else:path.parent.mkdir(parents=True,exist_ok=True);path.write_text(content)
if errors:
 print('\n'.join(errors[:30]));print(f'{len(errors)} localization errors');sys.exit(1)
print(f'{len(catalog)} keys validated in 6 languages; placeholders match.')
